#!/bin/bash
# Interactive self-host setup — answers a handful of questions and writes a
# ready-to-use .env, so a customer never opens a text editor or touches any
# code. No Node.js required (unlike scripts/generate-license-key.mjs, which
# is a Tollgate-internal tool the CUSTOMER never runs) — just bash, and
# openssl (or /dev/urandom as a fallback) for generating secrets, both of
# which are near-universal on anything that can run Docker.
#
# Usage:
#   ./scripts/setup-selfhost.sh
# Then:
#   docker compose -f docker-compose.selfhost.yml up -d --build
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

ENV_FILE=".env"

echo "Tollgate self-host setup"
echo "========================="
echo "This writes a .env file from your answers below — you won't need to"
echo "edit anything by hand afterward."
echo

if [ -f "$ENV_FILE" ]; then
  backup="${ENV_FILE}.bak.$(date +%Y%m%d%H%M%S)"
  cp "$ENV_FILE" "$backup"
  echo "Found an existing .env — backed it up to $backup before writing a new one."
  echo
fi

# openssl is near-universal on Docker hosts; /dev/urandom is the fallback
# for the rare host without it. Either way, no Node.js needed here.
gen_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 32
  else
    head -c 32 /dev/urandom | base64
  fi
}

ask() {
  local prompt="$1" default="$2" var
  read -r -p "$prompt [$default]: " var
  echo "${var:-$default}"
}

ask_required() {
  local prompt="$1" var
  while true; do
    read -r -p "$prompt: " var
    if [ -n "$var" ]; then
      echo "$var"
      return
    fi
    echo "  This one's required — Tollgate won't start without it." >&2
  done
}

ask_optional_secret() {
  # -s: doesn't echo the value to the terminal, same reason a password
  # prompt wouldn't — these are real API keys.
  local prompt="$1" var
  read -r -s -p "$prompt (press enter to skip): " var
  echo >&2
  echo "$var"
}

echo "--- Where this will run ---"
echo "If you're just trying this out on your own machine, the defaults"
echo "below are fine — press enter to accept each one."
echo
DASHBOARD_URL=$(ask "Dashboard URL (where people will sign in)" "http://localhost:3000")
API_URL=$(ask "API URL (must be reachable from browsers)" "http://localhost:4000")
PROXY_URL=$(ask "Proxy URL (where your agents will send requests — can be internal-only)" "http://localhost:8080")
echo

echo "--- License ---"
echo "The activation key Tollgate sent you (looks like two long strings"
echo "separated by a period)."
LICENSE_KEY=$(ask_required "License key")
echo

echo "--- Provider keys (optional) ---"
echo "Leave these blank if every org using this install will bring their own"
echo "OpenAI/Anthropic key (BYOK, configured later in the dashboard's"
echo "Settings page) rather than sharing one Tollgate-managed key."
OPENAI_KEY=$(ask_optional_secret "OpenAI API key")
ANTHROPIC_KEY=$(ask_optional_secret "Anthropic API key")
echo

echo "--- Cross-subdomain cookies (only if dashboard and API are on"
echo "    different subdomains of the same domain, e.g. app.company.com"
echo "    and api.company.com) ---"
COOKIE_DOMAIN=$(ask "Shared root domain (leading dot, e.g. .company.com) — leave blank if not applicable" "")
echo

echo "Generating secrets..."
VAULT_KEY=$(gen_secret)
AUTH_SECRET=$(gen_secret)
echo "  done."
echo

cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-selfhost.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)

REDIS_URL=redis://localhost:6379
DATABASE_URL=postgres://tollgate:tollgate@localhost:5432/tollgate

PROXY_PORT=8080
API_PORT=4000

NEXT_PUBLIC_API_URL=${API_URL}
NEXT_PUBLIC_PROXY_URL=${PROXY_URL}

OPENAI_UPSTREAM_KEY=${OPENAI_KEY}
CLAUDE_UPSTREAM_KEY=${ANTHROPIC_KEY}

VAULT_ENCRYPTION_KEY=${VAULT_KEY}

BETTER_AUTH_SECRET=${AUTH_SECRET}
BETTER_AUTH_URL=${API_URL}
DASHBOARD_ORIGIN=${DASHBOARD_URL}
AUTH_COOKIE_DOMAIN=${COOKIE_DOMAIN}

TOLLGATE_LICENSE_KEY=${LICENSE_KEY}
EOF

echo "Wrote $ENV_FILE."
echo
echo "Next step:"
echo "  docker compose -f docker-compose.selfhost.yml up -d --build"
echo
echo "(Once Tollgate has published a version you have registry access to,"
echo " 'docker compose -f docker-compose.selfhost.yml pull' then 'up -d'"
echo " works too, without needing this repo's source at all.)"
